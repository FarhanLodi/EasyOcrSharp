        // Distance is symmetric when insertion and deletion cost the same.
        Assert.Equal(expected, TextAccuracyMetrics.LevenshteinDistance(b, a));
        Assert.Equal(expected, NaiveLevenshtein(a.ToCharArray(), b.ToCharArray()));
    }

    [Fact]
    public void The_rolling_row_alignment_agrees_with_a_naive_full_matrix_over_a_fixed_corpus()
    {
        var mismatches = new List<string>();

        foreach (var (reference, hypothesis) in DeterministicPairs())
        {
            int expected = NaiveLevenshtein(reference.ToCharArray(), hypothesis.ToCharArray());

            int distance = TextAccuracyMetrics.LevenshteinDistance(reference, hypothesis);
            if (distance != expected)
            {
                mismatches.Add($"LevenshteinDistance('{reference}','{hypothesis}') = {distance}, expected {expected}");
            }

            int characters = TextAccuracyMetrics
                .Compare(reference, hypothesis, Unit(CharacterUnit.Utf16CodeUnit))
                .Characters.TotalErrors;
            if (characters != expected)
            {
                mismatches.Add($"Compare('{reference}','{hypothesis}').Characters = {characters}, expected {expected}");
            }

            int words = TextAccuracyMetrics.Compare(reference, hypothesis).Words.TotalErrors;
            int expectedWords = NaiveLevenshtein(Tokens(reference), Tokens(hypothesis));
            if (words != expectedWords)
            {
                mismatches.Add($"Compare('{reference}','{hypothesis}').Words = {words}, expected {expectedWords}");
            }
        }

        Assert.Empty(mismatches);
    }

    [Fact]
    public void Every_character_unit_agrees_with_the_naive_matrix_over_the_fixed_corpus()
    {
        var mismatches = new List<string>();

        foreach (var (reference, hypothesis) in DeterministicPairs())
        {
            // The corpus is pure ASCII, so all three counting units must produce identical numbers.
            int expected = NaiveLevenshtein(reference.ToCharArray(), hypothesis.ToCharArray());

            foreach (var unit in Enum.GetValues<CharacterUnit>())
            {
                var counts = TextAccuracyMetrics.Compare(reference, hypothesis, Unit(unit)).Characters;
                if (counts.TotalErrors != expected)
                {
                    mismatches.Add($"{unit}: '{reference}' vs '{hypothesis}' = {counts.TotalErrors}, expected {expected}");
                }
                if (counts.ReferenceLength != reference.Length || counts.HypothesisLength != hypothesis.Length)
                {
                    mismatches.Add($"{unit}: '{reference}' vs '{hypothesis}' recovered lengths " +
                        $"{counts.ReferenceLength}/{counts.HypothesisLength}, expected {reference.Length}/{hypothesis.Length}");
                }
            }
        }

        Assert.Empty(mismatches);
    }

    [Fact]
    public void The_fixed_corpus_actually_exercises_both_orderings_and_non_trivial_edits()
    {
        // A guard on the guard: if the generator ever degenerated to identical or empty pairs, the
        // cross-check tests above would pass without proving anything.
        var pairs = DeterministicPairs();

        Assert.Equal(80, pairs.Count);
        Assert.Contains(pairs, p => p.Reference.Length > p.Hypothesis.Length);
        Assert.Contains(pairs, p => p.Reference.Length < p.Hypothesis.Length);
        Assert.Contains(pairs, p => p.Reference.Length > 0 && p.Hypothesis.Length > 0 && p.Reference != p.Hypothesis);
        Assert.Contains(pairs, p => Tokens(p.Reference).Length > 1);
    }
