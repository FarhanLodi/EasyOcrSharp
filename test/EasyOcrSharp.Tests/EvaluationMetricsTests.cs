                new TextComparisonOptions { UnicodeNormalization = NormalizationForm.FormC }),
            10);
    }

    [Fact]
    public void Normalization_steps_run_in_a_fixed_order_so_combinations_do_not_interact()
    {
        // Punctuation is stripped before whitespace is collapsed, so removing the dash cannot leave a
        // double space behind.
        var options = new TextComparisonOptions { StripPunctuation = true, CollapseWhitespace = true };

        Assert.Equal("a b", TextAccuracyMetrics.Normalize("a - b", options));
        Assert.Equal("a b", TextAccuracyMetrics.Normalize("  a  ,  b  ", options));
    }

