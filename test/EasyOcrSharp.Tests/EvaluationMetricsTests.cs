    [Fact]
    public void Punctuation_stripping_removes_every_unicode_punctuation_category()
    {
        var options = new TextComparisonOptions { StripPunctuation = true };

        // Pc, Pd, Ps/Pe, Pi/Pf, Po — including the non-ASCII ones.
        Assert.Equal("ab", TextAccuracyMetrics.Normalize("a_b", options));
        Assert.Equal("ab", TextAccuracyMetrics.Normalize("a—b", options));
        Assert.Equal("ab", TextAccuracyMetrics.Normalize("a(b)", options));
        Assert.Equal("ab", TextAccuracyMetrics.Normalize("a«b»", options));
        Assert.Equal("ab", TextAccuracyMetrics.Normalize("a、b", options));
    }

    [Fact]
    public void Punctuation_stripping_keeps_currency_and_maths_symbols()
    {
        var options = new TextComparisonOptions { StripPunctuation = true };

        // char.IsPunctuation excludes the Sc/Sm categories, so a mangled amount still counts as an error.
        Assert.Equal("$5 + 3 = 8 €2", TextAccuracyMetrics.Normalize("$5 + 3 = 8 €2", options));
        Assert.Equal(1.0 / 2, TextAccuracyMetrics.CharacterErrorRate("$5", "5", options), 10);
    }

    [Fact]
    public void Punctuation_stripping_also_removes_the_percent_sign()
    {
        // Recorded as the shipped behaviour: '%' is Unicode category Po, so char.IsPunctuation reports it
        // and it is dropped, even though the XML documentation lists it as a symbol that survives.
        var options = new TextComparisonOptions { StripPunctuation = true };

        Assert.Equal("100", TextAccuracyMetrics.Normalize("100%", options));
        Assert.Equal(0.0, TextAccuracyMetrics.CharacterErrorRate("100%", "100", options), 10);
    }

    [Fact]
    public void Unicode_normalization_changes_the_score_only_when_it_is_enabled()
    {
        // Precomposed against decomposed: one grapheme each, but not the same grapheme.
        Assert.Equal(1.0, TextAccuracyMetrics.CharacterErrorRate(PrecomposedEAcute, DecomposedEAcute), 10);
        Assert.Equal(
            0.0,
            TextAccuracyMetrics.CharacterErrorRate(
                PrecomposedEAcute,
                DecomposedEAcute,
                new TextComparisonOptions { UnicodeNormalization = NormalizationForm.FormC }),
            10);
        Assert.Equal(
            0.0,
            TextAccuracyMetrics.CharacterErrorRate(
                PrecomposedEAcute,
                DecomposedEAcute,
                new TextComparisonOptions { UnicodeNormalization = NormalizationForm.FormD }),
            10);
    }

    [Fact]
    public void Compatibility_normalization_folds_full_width_digits_onto_ascii()
    {
        var kc = new TextComparisonOptions { UnicodeNormalization = NormalizationForm.FormKC };

        Assert.Equal("123", TextAccuracyMetrics.Normalize(FullWidthDigits, kc));
        Assert.Equal(0.0, TextAccuracyMetrics.CharacterErrorRate("123", FullWidthDigits, kc), 10);

        // Canonical composition alone does not fold compatibility variants.
        Assert.Equal(
            1.0,
