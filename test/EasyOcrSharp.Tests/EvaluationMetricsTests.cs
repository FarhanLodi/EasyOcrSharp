    [Fact]
    public void Whitespace_collapsing_makes_a_different_line_wrap_free_of_charge()
    {
        const string reference = "one two three";
        const string hypothesis = "one\ttwo\nthree";

        // Tabs and newlines are real character errors until collapsing is turned on...
        Assert.Equal(2.0 / 13, TextAccuracyMetrics.CharacterErrorRate(reference, hypothesis), 10);
        Assert.Equal(
            0.0,
            TextAccuracyMetrics.CharacterErrorRate(reference, hypothesis, new TextComparisonOptions { CollapseWhitespace = true }),
            10);
        // ...but the word level never saw them as anything but delimiters.
        Assert.Equal(0.0, TextAccuracyMetrics.WordErrorRate(reference, hypothesis), 10);
    }

    [Fact]
    public void Punctuation_stripping_changes_the_score_only_when_it_is_enabled()
    {
        const string reference = "Hello, world!";
        const string hypothesis = "Hello world";

