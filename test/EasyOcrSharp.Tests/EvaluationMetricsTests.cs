    [Fact]
    public void Word_metrics_are_case_and_punctuation_sensitive_until_told_otherwise()
    {
        // By default BOTH words differ — "Hello"/"hello" by case and "world"/"world!" by punctuation —
        // so that is two substitutions over a two-word reference: WER 1.0, not 0.5.
        Assert.Equal(1.0, TextAccuracyMetrics.WordErrorRate("Hello world", "hello world!"), 10);

        // Relaxed folds case and strips punctuation, so the same pair matches exactly.
        Assert.Equal(0.0, TextAccuracyMetrics.WordErrorRate("Hello world", "hello world!", TextComparisonOptions.Relaxed), 10);

