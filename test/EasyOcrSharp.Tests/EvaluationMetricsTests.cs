    [Fact]
    public void Identical_strings_score_zero_at_both_levels()
    {
        const string text = "the quick brown fox";

        var report = TextAccuracyMetrics.Compare(text, text);

        Assert.Equal(0.0, report.CharacterErrorRate, 10);
        Assert.Equal(0.0, report.WordErrorRate, 10);
        Assert.Equal(0.0, TextAccuracyMetrics.CharacterErrorRate(text, text), 10);
        Assert.Equal(0.0, TextAccuracyMetrics.WordErrorRate(text, text), 10);
        Assert.Equal(new ErrorCounts(19, 0, 0, 0), report.Characters);
        Assert.Equal(new ErrorCounts(4, 0, 0, 0), report.Words);
        Assert.Equal(1.0, report.Characters.Accuracy, 10);
    }

    [Fact]
    public void A_single_substitution_costs_one_error_over_the_reference_length()
    {
        var counts = TextAccuracyMetrics.Compare("kitten", "sitten").Characters;

        Assert.Equal(new ErrorCounts(5, 1, 0, 0), counts);
        Assert.Equal(1.0 / 6, counts.ErrorRate, 10);
        Assert.Equal(1.0 / 6, TextAccuracyMetrics.CharacterErrorRate("kitten", "sitten"), 10);
    }

