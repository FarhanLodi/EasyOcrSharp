    [Fact]
    public void Whitespace_collapsing_changes_the_score_only_when_it_is_enabled()
    {
        Assert.Equal(0.25, TextAccuracyMetrics.CharacterErrorRate("a  b", "a b"), 10);

        var options = new TextComparisonOptions { CollapseWhitespace = true };
        Assert.Equal(0.0, TextAccuracyMetrics.CharacterErrorRate("a  b", "a b", options), 10);
