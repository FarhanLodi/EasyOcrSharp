    // ---------------------------------------------------------------- helpers

    private static int GraphemeCount(string text) => Graphemes(text).Count;

    private static List<string> Graphemes(string text)
    {
        var elements = new List<string>();
        var enumerator = StringInfo.GetTextElementEnumerator(text);
        while (enumerator.MoveNext()) elements.Add(enumerator.GetTextElement());
        return elements;
    }

    private static string[] Tokens(string text)
        => text.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);

    /// <summary>
    /// The textbook full-matrix Levenshtein distance. Deliberately the naive O(n*m) memory version so it
    /// shares no code (and no bugs) with the two-rolling-rows implementation under test.
    /// </summary>
    private static int NaiveLevenshtein<T>(IReadOnlyList<T> a, IReadOnlyList<T> b)
        where T : IEquatable<T>
    {
        var d = new int[a.Count + 1, b.Count + 1];
        for (int i = 0; i <= a.Count; i++) d[i, 0] = i;
        for (int j = 0; j <= b.Count; j++) d[0, j] = j;

        for (int i = 1; i <= a.Count; i++)
        {
            for (int j = 1; j <= b.Count; j++)
            {
                int cost = a[i - 1].Equals(b[j - 1]) ? 0 : 1;
                d[i, j] = Math.Min(Math.Min(d[i - 1, j] + 1, d[i, j - 1] + 1), d[i - 1, j - 1] + cost);
            }
        }

        return d[a.Count, b.Count];
    }

    /// <summary>
    /// A fixed set of small string pairs for the cross-check tests. Generated by a hand-rolled xorshift
    /// with a hard-coded seed rather than <see cref="Random"/>, so the corpus is byte-for-byte the same
    /// on every machine, every run and every framework version.
    /// </summary>
    private static IReadOnlyList<(string Reference, string Hypothesis)> DeterministicPairs()
    {
        const string alphabet = "abcx ";
        uint state = 0x2545F491u;

        uint Next()
        {
            state ^= state << 13;
            state ^= state >> 17;
            state ^= state << 5;
            return state;
        }

        string Make(int length)
        {
            var chars = new char[length];
            for (int i = 0; i < length; i++) chars[i] = alphabet[(int)(Next() % (uint)alphabet.Length)];
            return new string(chars);
        }

        var pairs = new List<(string, string)>(80);
        for (int i = 0; i < 80; i++)
        {
            pairs.Add((Make((int)(Next() % 12u)), Make((int)(Next() % 12u))));
        }
        return pairs;
    }

