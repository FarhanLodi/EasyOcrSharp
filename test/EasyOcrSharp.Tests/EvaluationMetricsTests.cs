    [Fact]
    public void An_unpaired_surrogate_becomes_a_replacement_character_when_counting_runes()
    {
        // Rune enumeration cannot represent a lone surrogate, so it surfaces as U+FFFD — which still
        // compares equal to the same malformed input, and unequal to the well-formed neighbour.
        const string malformed = "a\ud800b";

        Assert.Equal(0.0, TextAccuracyMetrics.CharacterErrorRate(malformed, malformed, Unit(CharacterUnit.Rune)), 10);
        Assert.Equal(1.0 / 3, TextAccuracyMetrics.CharacterErrorRate(malformed, "ab", Unit(CharacterUnit.Rune)), 10);
    }

    // ---------------------------------------------------------------- breakdown consistency

    [Theory]
    [InlineData("", "")]
    [InlineData("", "hello world")]
    [InlineData("hello world", "")]
    [InlineData("the quick brown fox", "the quick brown fox")]
    [InlineData("the quick brown fox", "teh quikc brwon fox jumps")]
    [InlineData("one", "one two three four five")]
    [InlineData("a b c d e", "a")]
    [InlineData("café naïve", "cafe naive")]
    [InlineData("日本語 テスト", "日本語")]
    [InlineData("smile \U0001F600 now", "smile now")]
    public void The_breakdown_is_internally_consistent_with_the_rates_and_the_input_lengths(
        string reference,
        string hypothesis)
    {
        var report = TextAccuracyMetrics.Compare(reference, hypothesis);

        AssertConsistent(report.Characters, GraphemeCount(reference), GraphemeCount(hypothesis));
        AssertConsistent(report.Words, Tokens(reference).Length, Tokens(hypothesis).Length);

        Assert.Equal(report.Characters.ErrorRate, report.CharacterErrorRate, 10);
        Assert.Equal(report.Words.ErrorRate, report.WordErrorRate, 10);

        // The rates the shorthand entry points return must be the same numbers the report carries.
        Assert.Equal(report.CharacterErrorRate, TextAccuracyMetrics.CharacterErrorRate(reference, hypothesis), 10);
        Assert.Equal(report.WordErrorRate, TextAccuracyMetrics.WordErrorRate(reference, hypothesis), 10);

        // ...and the totals must equal a minimal edit distance computed the naive way.
        Assert.Equal(NaiveLevenshtein(Graphemes(reference), Graphemes(hypothesis)), report.Characters.TotalErrors);
        Assert.Equal(NaiveLevenshtein(Tokens(reference), Tokens(hypothesis)), report.Words.TotalErrors);
    }

    private static void AssertConsistent(ErrorCounts counts, int referenceLength, int hypothesisLength)
    {
        Assert.Equal(referenceLength, counts.ReferenceLength);
        Assert.Equal(hypothesisLength, counts.HypothesisLength);
        Assert.Equal(referenceLength, counts.Hits + counts.Substitutions + counts.Deletions);
        Assert.Equal(hypothesisLength, counts.Hits + counts.Substitutions + counts.Insertions);
        Assert.Equal(counts.Substitutions + counts.Insertions + counts.Deletions, counts.TotalErrors);

        // Every edit is accounted for: the surplus of insertions over deletions is exactly the length gap.
        Assert.Equal(hypothesisLength - referenceLength, counts.Insertions - counts.Deletions);

        Assert.True(counts.Hits >= 0 && counts.Substitutions >= 0 && counts.Insertions >= 0 && counts.Deletions >= 0);

        double expectedRate = referenceLength == 0
            ? (counts.TotalErrors == 0 ? 0.0 : 1.0)
            : (double)counts.TotalErrors / referenceLength;
        Assert.Equal(expectedRate, counts.ErrorRate, 10);
        Assert.Equal(Math.Clamp(1.0 - expectedRate, 0.0, 1.0), counts.Accuracy, 10);
        Assert.InRange(counts.Accuracy, 0.0, 1.0);
    }

    [Fact]
    public void Error_counts_are_an_immutable_value_with_structural_equality()
    {
        var counts = new ErrorCounts(3, 1, 2, 0);
        var changed = counts with { Insertions = 5 };

